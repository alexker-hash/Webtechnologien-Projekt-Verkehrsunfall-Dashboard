let markerLayer = null;  // global definierter Layer
function initMap() {
    map = L.map('mymap', {
        center: [50, 8],
        zoom: 14
    });
    L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        maxZoom: 18,
        attribution: '© OpenStreetMap contributors'
    }).addTo(map);
    markerLayer = L.layerGroup().addTo(map);  // global definierter Layer

    initMarkers();
    return map;
}
